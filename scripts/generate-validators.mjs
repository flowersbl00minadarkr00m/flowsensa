import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const readSchema = async (relativePath) =>
  JSON.parse(await readFile(new URL(relativePath, import.meta.url), "utf8"));

const workEventSchema = await readSchema("../src/schemas/work-event.schema.json");
const workPrimitivesSchema = await readSchema("../src/schemas/work-primitives.schema.json");

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true },
});
addFormats(ajv, { mode: "fast" });
ajv.addSchema(workEventSchema);
ajv.addSchema(workPrimitivesSchema);

const generated = standaloneCode(ajv, {
  validateWorkEvents: workEventSchema.$id,
  validatePrimitiveRegistry: workPrimitivesSchema.$id,
});
const banner =
  "/* oxlint-disable */\n// @ts-nocheck\n// Generated by scripts/generate-validators.mjs. Do not edit by hand.\n";
const outputUrl = new URL("../src/generated/validators.ts", import.meta.url);
await writeFile(outputUrl, `${banner}${generated}\n`, "utf8");
console.log(`Generated ${fileURLToPath(outputUrl)}`);
